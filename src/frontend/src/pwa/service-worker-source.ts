/** A file of the built SPA: its path under dist/ ("/" separated) and its bytes. */
export interface BuiltFile {
  path: string;
  content: Uint8Array;
}

export interface ServiceWorker {
  version: string;
  precache: string[];
  source: string;
}

const NOT_PRECACHED = [/^sw\.js$/, /\.map$/, /^\.vite\//];

/**
 * dist/sw.js for a build: VERSION, PRECACHE, the shell, then the service's extensions. The version
 * is a hash of every built file and of the worker's own sources, so any change to the build changes
 * sw.js, which is what makes a browser install the new worker.
 */
export async function serviceWorkerSource(
  files: BuiltFile[],
  shell: string,
  extensions: string,
): Promise<ServiceWorker> {
  const built = files
    .filter((file) => !NOT_PRECACHED.some((pattern) => pattern.test(file.path)))
    .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));

  const parts: string[] = [];
  for (const file of built) parts.push(`${file.path}\0${await sha256(file.content)}`);
  parts.push(shell, extensions);
  const version = (await sha256(new TextEncoder().encode(parts.join("\0")))).slice(0, 12);

  const precache = built.map((file) => `/${file.path}`);
  const source = [
    "// Generated by the build (vite-plugin-sw.ts) from src/sw/: edit those, not this.",
    `const VERSION = ${JSON.stringify(version)};`,
    `const PRECACHE = ${JSON.stringify(precache)};`,
    "",
    shell.trimEnd(),
    "",
    extensions.trimEnd(),
    "",
  ].join("\n");
  return { version, precache, source };
}

async function sha256(bytes: Uint8Array): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", bytes as Uint8Array<ArrayBuffer>);
  return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, "0")).join("");
}
